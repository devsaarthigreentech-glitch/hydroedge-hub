"""Regenerate db/migrations/030_nano_registry_generations.sql from the two
firmware config tables (NanoV3 and Gen 2 nano_iot_firmware).

    python scripts/gen_registry_generations.py db/migrations/030_nano_registry_generations.sql

Firmware checkouts are expected under C:/SGTFirmware; edit V3 / G2 below if not.
"""
import re, subprocess, sys
rx = re.compile(r'\{"(P-\d+)","(P_\d+)","([^"]*)",(CT_\w+),"([^"]*)",([^,]+),([^,]+),(\w+),(\w+),(\w+),"([^"]*)","([^"]*)"\}')
V3 = r"C:/SGTFirmware/NanoV3"; G2 = r"C:/SGTFirmware/nano_iot_firmware"
T = "components/config_manager/config_table.c"
def pids(repo):
    return [m.group(1) for m in rx.finditer(open(f"{repo}/{T}", encoding="utf-8").read())]
def sha(repo):
    return subprocess.check_output(["git", "-C", repo, "log", "-1", "--format=%h", "--", T], text=True).strip()
v3, g2 = pids(V3), pids(G2)
sv3, sg2 = set(v3), set(g2)
assert len(v3) == len(sv3) and len(g2) == len(sg2)
k = lambda p: int(p[2:])
both = sorted(sv3 & sg2, key=k); v3only = sorted(sv3 - sg2, key=k); g2only = sorted(sg2 - sv3, key=k)

def arr(lst, per=12):
    rows = [", ".join(f"'{p}'" for p in lst[i:i+per]) for i in range(0, len(lst), per)]
    return "ARRAY[\n    " + ",\n    ".join(rows) + "\n  ]"

out = f"""-- ============================================================================
-- 030: which firmware generation each registry parameter belongs to
-- ----------------------------------------------------------------------------
-- nano_registry holds the old Gen 2 Nano parameters (nano_iot_firmware) and
-- NanoV3's side by side, so the Config tab showed apparent duplicates such as
-- P-3020 (Gen 2 Battery System Voltage) next to P-5021 (NanoV3's). The new
-- generations column lets the Config tab show one generation at a time.
--
-- GENERATED by parsing both firmware config tables; do not hand-edit the lists:
--   NanoV3 {T} @ {sha(V3)}: {len(v3)} params
--   Gen 2  {T} @ {sha(G2)}: {len(g2)} params
--   shared IDs: {len(both)}
-- A registry row in neither table counts as Gen 2. Rows added later without a
-- value are classified by the API from their source column.
-- Re-runnable.
-- ============================================================================

ALTER TABLE nano_registry ADD COLUMN IF NOT EXISTS generations text[];

UPDATE nano_registry SET generations = CASE
  WHEN pid = ANY ({arr(both)}) THEN '{{NanoV3,Gen2}}'::text[]
  WHEN pid = ANY ({arr(v3only)}) THEN '{{NanoV3}}'::text[]
  ELSE '{{Gen2}}'::text[]
END;

DO $$
DECLARE n_both integer; n_v3 integer; n_g2 integer; n_null integer;
BEGIN
  SELECT count(*) FILTER (WHERE generations = '{{NanoV3,Gen2}}'),
         count(*) FILTER (WHERE generations = '{{NanoV3}}'),
         count(*) FILTER (WHERE generations = '{{Gen2}}'),
         count(*) FILTER (WHERE generations IS NULL)
    INTO n_both, n_v3, n_g2, n_null
    FROM nano_registry;
  IF n_null > 0 THEN
    RAISE EXCEPTION 'nano_registry: % row(s) left without generations', n_null;
  END IF;
  IF n_both + n_v3 = 0 THEN
    RAISE EXCEPTION 'nano_registry: no NanoV3 parameters found; is this the right database?';
  END IF;
  RAISE NOTICE 'nano_registry generations: % NanoV3 only, % Gen 2 only, % both (firmware tables: {len(v3only)} / {len(g2only)} / {len(both)})',
    n_v3, n_g2, n_both;
END $$;
"""
open(sys.argv[1], "w", encoding="utf-8", newline="\n").write(out)
print(len(v3only), len(g2only), len(both))
